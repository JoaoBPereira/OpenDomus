const currentSchemaVersion = 3

// EnsureDatabase creates the database of cfg when it does not exist, through the maintenance
// database "postgres" of the same server.
func EnsureDatabase(ctx context.Context, cfg config.Database) error {
	connection, err := pgx.Connect(ctx, cfg.URL("postgres"))
	if err != nil {
		return fmt.Errorf("connecting to the postgres maintenance database (check DB_HOST, DB_PORT, DB_USER and DB_PASSWORD): %w", err)
	}
	defer connection.Close(ctx)

	var exists bool
	err = connection.QueryRow(ctx, "SELECT EXISTS (SELECT 1 FROM pg_database WHERE datname = $1)", cfg.Name).Scan(&exists)
	if err != nil {
		return fmt.Errorf("checking database %q: %w", cfg.Name, err)
	}
	if exists {
		slog.Info("database exists", "name", cfg.Name)
		return nil
	}

	slog.Info("database does not exist, creating it", "name", cfg.Name)
	statement := fmt.Sprintf("CREATE DATABASE %s WITH OWNER = postgres ENCODING = 'UTF8' TABLESPACE = pg_default CONNECTION LIMIT = -1 IS_TEMPLATE = False", pgx.Identifier{cfg.Name}.Sanitize())
	if _, err := connection.Exec(ctx, statement); err != nil {
		return fmt.Errorf("creating database %q: %w", cfg.Name, err)
	}
	slog.Info("database created", "name", cfg.Name)
	return nil
}

// Migrate creates the schema_version table and applies the migrations newer than the stored version
func (db *DB) Migrate(ctx context.Context) error {
	_, err := db.Exec(ctx, `
		CREATE TABLE IF NOT EXISTS public.schema_version (
			version INTEGER PRIMARY KEY,
			applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
		)`)
	if err != nil {
		return fmt.Errorf("database connection failed (check DB_HOST, DB_PORT, DB_NAME, DB_USER and DB_PASSWORD): %w", err)
	}

	var versions []struct {
		Version int `db:"version"`
	}
	if err := db.QueryInto(ctx, &versions, "SELECT COALESCE(MAX(version), 0) AS version FROM public.schema_version"); err != nil {
		return err
	}
	installed := 0
	if len(versions) > 0 {
		installed = versions[0].Version
	}
	if installed >= currentSchemaVersion {
		return nil
	}
	slog.Info("schema update needed", "from", installed, "to", currentSchemaVersion)

	migrations := []struct {
		version int
		apply   func(context.Context) error
	}{
		{1, db.migrateV1},
		{2, db.migrateV2},
		{3, db.migrateV3},
	}
	for _, migration := range migrations {
		if migration.version <= installed {
			continue
		}
		if err := migration.apply(ctx); err != nil {
			return fmt.Errorf("migration v%d: %w", migration.version, err)
		}
		if _, err := db.Exec(ctx, "INSERT INTO schema_version (version) VALUES ($1)", migration.version); err != nil {
			return err
		}
		slog.Info("applied migration", "version", migration.version)
	}
	return nil
}

// migrateV1 is the initial schema
func (db *DB) migrateV1(ctx context.Context) error {
	// 1. Sequences
	_, err := db.Exec(ctx, `
      CREATE SEQUENCE IF NOT EXISTS public.users_id_seq INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1;
      CREATE SEQUENCE IF NOT EXISTS public.device_id_seq INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1;
      CREATE SEQUENCE IF NOT EXISTS public.tag_id_seq INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1;
      CREATE SEQUENCE IF NOT EXISTS public.tagvaluelocation_id_seq INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1;
    `)
	if err != nil {
		return err
	}

	// 2. Tables
	_, err = db.Exec(ctx, `
      CREATE TABLE IF NOT EXISTS public.users (
        id integer NOT NULL DEFAULT nextval('public.users_id_seq'::regclass),
        username text NOT NULL,
        password_hash text NOT NULL,
        role character varying(50) NOT NULL DEFAULT 'user'::character varying,
        CONSTRAINT users_pkey PRIMARY KEY (id),
        CONSTRAINT users_username_key UNIQUE (username)
      );

      CREATE TABLE IF NOT EXISTS public.log (
        date timestamp without time zone,
        level character varying(20),
        message text
      );

      CREATE TABLE IF NOT EXISTS public.device (
        id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 ),
        type character varying(64),
        url character varying(2048),
        name character varying(256),
        periodicity character varying(64),
        enabled boolean DEFAULT false,
        config text,
        CONSTRAINT device_pkey PRIMARY KEY (id)
      );

      CREATE TABLE IF NOT EXISTS public.tag (
        id integer NOT NULL DEFAULT nextval('public.tag_id_seq'::regclass),
        name character varying(250) NOT NULL,
        value_type character varying(25),
        config text,
        device_id integer,
        periodicity_count integer,
        type character varying(20),
        value_storage character varying(32) DEFAULT 'insert'::character varying,
        expires_in integer DEFAULT 0,
        enabled boolean DEFAULT true,
        display_in character varying[],
        CONSTRAINT tag_pkey PRIMARY KEY (id),
        CONSTRAINT device_id_fk FOREIGN KEY (device_id) REFERENCES public.device (id) ON UPDATE NO ACTION ON DELETE NO ACTION
      );

      CREATE TABLE IF NOT EXISTS public.tagvalueboolean (
        tag_id integer NOT NULL,
        "time" timestamp with time zone NOT NULL,
        value boolean,
        CONSTRAINT tagvalueboolean_pk PRIMARY KEY (tag_id, "time"),
        CONSTRAINT tagvalueboolean_tag_id_fkey FOREIGN KEY (tag_id) REFERENCES public.tag (id) ON UPDATE NO ACTION ON DELETE NO ACTION
      );

      CREATE TABLE IF NOT EXISTS public.tagvaluefloat (
        tag_id integer NOT NULL,
        "time" timestamp with time zone NOT NULL,
        value double precision,
        CONSTRAINT tagvalue_pk PRIMARY KEY (tag_id, "time"),
        CONSTRAINT tagvaluefloat_tag_id_fkey FOREIGN KEY (tag_id) REFERENCES public.tag (id) ON UPDATE NO ACTION ON DELETE NO ACTION
      );

      CREATE TABLE IF NOT EXISTS public.tagvaluelocation (
        id integer NOT NULL DEFAULT nextval('public.tagvaluelocation_id_seq'::regclass),
        tag_id integer NOT NULL,
        latitude double precision NOT NULL,
        longitude double precision NOT NULL,
        accuracy double precision,
        altitude double precision,
        speed double precision,
        "time" timestamp with time zone DEFAULT now(),
        CONSTRAINT tagvaluelocation_pkey PRIMARY KEY (id),
        CONSTRAINT tagvaluelocation_tag_id_fkey FOREIGN KEY (tag_id) REFERENCES public.tag (id) ON UPDATE NO ACTION ON DELETE NO ACTION
      );
    `)
	if err != nil {
		return err
	}

	// 3. Sequence ownership, now that the tables exist
	_, err = db.Exec(ctx, `
      ALTER SEQUENCE public.users_id_seq OWNED BY public.users.id;
      ALTER SEQUENCE public.tag_id_seq OWNED BY public.tag.id;
      ALTER SEQUENCE public.tagvaluelocation_id_seq OWNED BY public.tagvaluelocation.id;
    `)
	if err != nil {
		return err
	}

	// 4. Indexes and the TimescaleDB hypertable
	_, err = db.Exec(ctx, `
      CREATE INDEX IF NOT EXISTS tagvaluefloat_time_date_idx ON public.tagvaluefloat USING btree ("time" ASC NULLS LAST);
      SELECT create_hypertable('public.tagvaluefloat', 'time');
    `)
	return err
}

// migrateV2 adds the users.role column to databases created before it existed and gives the
// admin user the admin role (this used to run on every start)
func (db *DB) migrateV2(ctx context.Context) error {
	_, err := db.Exec(ctx, `
      ALTER TABLE public.users ADD COLUMN IF NOT EXISTS role VARCHAR(50) NOT NULL DEFAULT 'user';
      UPDATE public.users SET role = 'admin' WHERE username = 'admin';
    `)
	return err
}

// migrateV3 adds the automations: a graph of triggers, logic gates and actions (see models.Automation)
func (db *DB) migrateV3(ctx context.Context) error {
	_, err := db.Exec(ctx, `
      CREATE TABLE IF NOT EXISTS public.automation (
        id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name character varying(256) NOT NULL,
        enabled boolean NOT NULL DEFAULT true,
        graph jsonb NOT NULL
      );
    `)
	return err
}
